export const getWeatherSvg = (condition?: string): TemplateResult => {
  if (!condition) return clearSkySvg;
  const mapped = WEATHER_ICON_MAP[condition.toLowerCase()] || condition;
  switch (mapped) {
    case 'night-clear-sky':
      return nightClearSkySvg;
    case 'new-clouds':
      return newCloudsSvg;
    case 'scattered-clouds':
      return scatteredCloudsSvg;
    case 'rain':
      return rainSvg;
    case 'snow':
      return snowSvg;
    case 'clear-sky':
    default:
      return clearSkySvg;
  }
};
